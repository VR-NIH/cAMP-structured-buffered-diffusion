    f.write(f"One-scale product comparison R^2 = {r2:.6f}\n")
    f.write("Scope: supports mean-field factorization of release-recapture mobility in the tested fast-exchange, local-capture regime; does not derive the continuum PDE or calibrate D_relay,0.\n")

